export const BUILTIN_FOODS: FoodItem[] = rows.map((r, i) => ({
  id: `b${i}`,
  name: r[0],
  unit: r[7] ?? 'g',
  baseQty: 100,
  kcal: r[1],
  protein: r[2],
  carbs: r[3],
  fat: r[4],
  serving: { label: r[5], qty: r[6] },
  source: 'builtin',
}));

export function searchBuiltin(q: string): FoodItem[] {
  const words = q.toLowerCase().split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  return BUILTIN_FOODS.filter((f) => {
    const n = f.name.toLowerCase();
    return words.every((w) => n.includes(w));
  });
}
